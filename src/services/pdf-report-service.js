// services/pdf-report-service.js
import jsPDF from 'jspdf';
import autoTable from 'jspdf-autotable';

const truncate = (text, max) => {
  if (!text) return '-';
  return text.length > max ? text.slice(0, max - 1) + '…' : text;
};

const statusLabel = (req) => {
  if (req.status === 'approved') return 'Approved';
  return req.is_ambiguous ? 'Ambiguous' : 'Clear';
};

/**
 * Generates and downloads a client-facing PDF summary for a project:
 * cover section, executive summary stats, batch breakdown table, and a
 * full requirements detail table. Runs entirely client-side — no backend call.
 */
export function generateProjectReport({ project, batches, requirements, generatedByEmail }) {
  const doc = new jsPDF({ unit: 'pt', format: 'a4' });
  const pageWidth = doc.internal.pageSize.getWidth();
  const pageHeight = doc.internal.pageSize.getHeight();
  const margin = 40;
  let y = 60;

  // ── Cover / Header ──────────────────────────────────────────
  doc.setFontSize(20);
  doc.setFont(undefined, 'bold');
  doc.text('Requirements Analysis Report', margin, y);
  y += 28;

  doc.setFontSize(14);
  doc.setFont(undefined, 'normal');
  doc.text(project?.name || 'Untitled Project', margin, y);
  y += 20;

  if (project?.description) {
    doc.setFontSize(10);
    doc.setTextColor(100);
    const descLines = doc.splitTextToSize(project.description, pageWidth - margin * 2);
    doc.text(descLines, margin, y);
    y += descLines.length * 12 + 10;
    doc.setTextColor(0);
  }

  doc.setFontSize(9);
  doc.setTextColor(120);
  doc.text(`Generated: ${new Date().toLocaleString()}`, margin, y);
  y += 14;
  if (generatedByEmail) {
    doc.text(`Generated by: ${generatedByEmail}`, margin, y);
    y += 14;
  }
  doc.setTextColor(0);
  y += 8;

  doc.setDrawColor(220);
  doc.line(margin, y, pageWidth - margin, y);
  y += 25;

  // ── Executive Summary ───────────────────────────────────────
  const totalCount = requirements.length;
  const ambiguousCount = requirements.filter((r) => r.is_ambiguous && r.status !== 'approved').length;
  const clearCount = totalCount - ambiguousCount;
  const approvedCount = requirements.filter((r) => r.status === 'approved').length;
  const pushedCount = requirements.filter((r) => r.jira_issue_key).length;
  const pct = (n) => (totalCount ? Math.round((n / totalCount) * 100) : 0);

  doc.setFontSize(14);
  doc.setFont(undefined, 'bold');
  doc.text('Executive Summary', margin, y);
  y += 20;

  doc.setFontSize(10);
  doc.setFont(undefined, 'normal');
  [
    `Total Requirements Evaluated: ${totalCount}`,
    `Ambiguous: ${ambiguousCount} (${pct(ambiguousCount)}%)`,
    `Clear: ${clearCount} (${pct(clearCount)}%)`,
    `Approved & Refined: ${approvedCount} (${pct(approvedCount)}%)`,
    `Pushed to Jira: ${pushedCount} (${pct(pushedCount)}%)`,
  ].forEach((line) => {
    doc.text(line, margin, y);
    y += 16;
  });
  y += 8;

  // ── Batch Breakdown Table ───────────────────────────────────
  doc.setFontSize(14);
  doc.setFont(undefined, 'bold');
  doc.text('Batch Breakdown', margin, y);

  const batchRows = batches.map((batch) => {
    const batchReqs = requirements.filter((r) => r.batch_id === batch.id);
    const batchAmbiguous = batchReqs.filter((r) => r.is_ambiguous && r.status !== 'approved').length;
    return [
      `#${batch.batch_number}`,
      batch.file_name || '-',
      new Date(batch.created_at).toLocaleDateString(),
      String(batchReqs.length),
      String(batchAmbiguous),
      String(batchReqs.length - batchAmbiguous),
    ];
  });

  autoTable(doc, {
    startY: y + 8,
    margin: { left: margin, right: margin },
    head: [['Batch', 'File Name', 'Date', 'Total', 'Ambiguous', 'Clear']],
    body: batchRows.length ? batchRows : [['-', 'No batches', '-', '-', '-', '-']],
    styles: { fontSize: 9, cellPadding: 5 },
    headStyles: { fillColor: [30, 41, 59] },
    theme: 'grid',
  });

  y = doc.lastAutoTable.finalY + 30;

  // ── Requirements Detail Table ───────────────────────────────
  if (y > pageHeight - 120) {
    doc.addPage();
    y = 50;
  }

  doc.setFontSize(14);
  doc.setFont(undefined, 'bold');
  doc.text('Requirements Detail', margin, y);

  const reqRows = requirements.map((req, idx) => [
    String(idx + 1),
    truncate(req.story_text, 90),
    statusLabel(req),
    req.status === 'approved' ? truncate(req.improved_version, 90) : '-',
    req.jira_issue_key || '-',
  ]);

  autoTable(doc, {
    startY: y + 8,
    margin: { left: margin, right: margin },
    head: [['#', 'Original Story', 'Status', 'Refined Version', 'Jira']],
    body: reqRows.length ? reqRows : [['-', 'No requirements found', '-', '-', '-']],
    styles: { fontSize: 8, cellPadding: 4, overflow: 'linebreak' },
    headStyles: { fillColor: [30, 41, 59] },
    theme: 'grid',
    columnStyles: {
      0: { cellWidth: 25 },
      1: { cellWidth: 165 },
      2: { cellWidth: 55 },
      3: { cellWidth: 165 },
      4: { cellWidth: 55 },
    },
  });

  // ── Footer: page numbers on every page ──────────────────────
  const totalPages = doc.internal.getNumberOfPages();
  for (let i = 1; i <= totalPages; i++) {
    doc.setPage(i);
    doc.setFontSize(8);
    doc.setTextColor(150);
    doc.text('Generated by Req-Analyzer', margin, pageHeight - 20);
    doc.text(`Page ${i} of ${totalPages}`, pageWidth - margin - 60, pageHeight - 20);
  }

  const safeName = (project?.name || 'project').replace(/[^a-z0-9]+/gi, '-').toLowerCase();
  doc.save(`req-analyzer-report-${safeName}-${Date.now()}.pdf`);
}